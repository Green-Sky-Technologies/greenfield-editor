"""Regenerates the editor's Greenfield marks (Story 2.2) from the brand SVGs next to index.html.

  assets/app-icon/greenfield-<n>.png           the favicon tile (mark on #070709) at whole
                                                multiples of its 16-unit grid: 16 to 1024
  crates/ui-egui/src/greenfield_mark.rs       the 16x16 mark as two row bitmaps (ink cells and
                                                field cells), which the UI paints cell by cell
Pixel art: nearest-neighbour scaling only, so edges stay crisp.

Usage: python3 greenfield/tools/gen-marks.py   (needs Pillow)
"""

import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent.parent
PUBLIC = ROOT / "apps" / "figcraft-web"
CELL = re.compile(r"M(\d+) (\d+)h1v1h-1z")


def cells(svg: str):
    """(fill, set of (x, y)) per <path> of unit cells."""
    return [(fill, {(int(x), int(y)) for x, y in CELL.findall(d)}) for d, fill in re.findall(r'<path d="([^"]*)" fill="(#[0-9a-f]{6})"', svg)]


def rgb(h: str):
    return tuple(int(h[i : i + 2], 16) for i in (1, 3, 5))


# --- app icon PNGs: the favicon tile ---------------------------------------------------------
fav = (PUBLIC / "greenfield-favicon.svg").read_text()
tile = rgb(re.search(r'<rect[^>]*fill="(#[0-9a-f]{6})"', fav).group(1))
base = Image.new("RGB", (16, 16), tile)
for fill, xy in cells(fav):
    for x, y in xy:
        base.putpixel((x, y), rgb(fill))
out = ROOT / "assets" / "app-icon"
out.mkdir(parents=True, exist_ok=True)
for n in (16, 32, 48, 64, 128, 256, 512, 1024):
    base.resize((n, n), Image.NEAREST).save(out / f"greenfield-{n}.png", optimize=True)

# --- the in-UI mark: ink cells and field cells of the small mark -----------------------------
small = cells((PUBLIC / "greenfield-mark-small.svg").read_text())
ink = next(xy for fill, xy in small if fill == "#ece8de")
field = next(xy for fill, xy in small if fill == "#3fd67f")


def rows(xy):
    return [sum(1 << x for x in range(16) if (x, y) in xy) for y in range(16)]


def fmt(name, doc, xy):
    body = ", ".join(f"0x{r:04X}" for r in rows(xy))
    return f"/// {doc}\npub const {name}: [u16; 16] = [{body}];\n"


rs = ROOT / "crates" / "ui-egui" / "src" / "greenfield_mark.rs"
rs.parent.mkdir(parents=True, exist_ok=True)
rs.write_text(
    "//! Greenfield's small mark (`apps/figcraft-web/greenfield-mark-small.svg`, Story 2.2) as 16 row\n"
    "//! bitmaps, bit `x` of row `y` being the cell at (x, y). Generated by\n"
    "//! `greenfield/tools/gen-marks.py`; do not edit.\n\n"
    + fmt("INK", "The selection box and handles: `ink` colour.", ink)
    + "\n"
    + fmt("FIELD", "The dithered field rising inside it: `field` colour.", field)
)
print("ok")
